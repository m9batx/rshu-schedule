@limiter.limit("5 per minute", methods=["POST"])
def admin_login():
    if request.method == "POST":
        password = request.form.get("password", "")
        try:
            ok = bcrypt.checkpw(password.encode("utf-8"), ADMIN_PASSWORD_HASH)
        except Exception as e:
            log.warning(f"bcrypt error: {e}")
            ok = False

        if ok:
            session.clear()
            session["is_admin"] = True
            log.info("Admin login from %s", get_remote_address())
            return redirect(url_for("admin_panel"))

        log.warning("Failed admin login from %s", get_remote_address())
        flash("Wrong password.", "error")

    return render_template("admin_login.html", admin_user=ADMIN_USER)


