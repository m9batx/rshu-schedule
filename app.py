@app.route("/admin/settings", methods=["POST"])
@admin_required
def admin_save_settings():
    """
    Save current_year and max_age_years from the admin form.
    Both are validated: current_year ∈ [0..99], max_age_years ∈ [0..30].
    """
    cur_raw = request.form.get("current_year", "").strip()
    age_raw = request.form.get("max_age_years", "").strip()

    if not cur_raw.isdigit() or not (0 <= int(cur_raw) <= 99):
        flash("Current year must be a 2-digit number (00–99).", "error")
        return redirect(url_for("admin_panel"))

    if not age_raw.isdigit() or not (0 <= int(age_raw) <= 30):
        flash("Max age must be an integer between 0 and 30.", "error")
        return redirect(url_for("admin_panel"))

    set_setting("current_year", cur_raw)
    set_setting("max_age_years", age_raw)
    flash(f"Settings saved: current_year={cur_raw}, max_age_years={age_raw}", "success")
    return redirect(url_for("admin_panel"))


# ==================== CLEANUP BY AGE ====================
@app.route("/admin/cleanup-by-age", methods=["POST"])
@admin_required
def admin_cleanup_by_age():
    """
    Delete every group older than `max_age_years` relative to `current_year`.
    Uses the settings saved in the DB.
    """
    try:
        current_year = int(get_setting("current_year", "26"))
        max_age = int(get_setting("max_age_years", "5"))
    except ValueError:
        flash("Invalid stored settings.", "error")
        return redirect(url_for("admin_panel"))

    removed = []
    for g in list_groups():
        if is_older_than(g, current_year, max_age):
            delete_group(g)
            removed.append(g)

    if removed:
        flash(
            f"Removed {len(removed)} group(s) older than {max_age} years "
            f"(relative to {current_year}): {', '.join(removed)}",
            "success"
        )
    else:
        flash(
            f"Nothing to clean — no groups older than {max_age} years "
            f"relative to {current_year}.",
            "success"
        )
    return redirect(url_for("admin_panel"))


