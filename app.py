ALLOWED_EXT = {".pdf"}
MAX_PDF_BYTES = 20 * 1024 * 1024


@app.route("/admin/panel", methods=["GET", "POST"])
@admin_required
def admin_panel():
    if request.method == "POST":
        pdf = request.files.get("pdf")
        if not pdf or not pdf.filename:
            flash("No file selected.", "error")
            return redirect(url_for("admin_panel"))

        ext = os.path.splitext(pdf.filename)[1].lower()
        if ext not in ALLOWED_EXT:
            flash("Only .pdf files are allowed.", "error")
            return redirect(url_for("admin_panel"))

        pdf.stream.seek(0, os.SEEK_END)
        size = pdf.stream.tell()
        pdf.stream.seek(0)
        if size > MAX_PDF_BYTES:
            flash("File too large (max 20 MB).", "error")
            return redirect(url_for("admin_panel"))

        safe_name = secure_filename(pdf.filename) or "upload.pdf"
        safe_name = f"{secrets.token_hex(4)}_{safe_name}"
        save_path = os.path.join(UPLOAD_DIR, safe_name)
        pdf.save(save_path)

        try:
            group = extract_group(save_path)
            if not is_valid_group(group):
                raise ValueError(f"Invalid group name: {group}")
            schedule = extract_schedule(save_path)
            save_schedule(group, schedule, safe_name)
            flash(f"Uploaded & parsed group: {group}", "success")
            log.info("Uploaded schedule for %s", group)
        except Exception as e:
            log.exception("Parse failed")
            flash(f"Failed to parse PDF: {e}", "error")

        return redirect(url_for("admin_panel"))

    settings = get_all_settings()
    groups = list_groups()
    return render_template(
        "admin.html",
        groups=groups,
        group_rows=list_groups_with_counts(),
        settings=settings,
        admin_user=ADMIN_USER,
    )


