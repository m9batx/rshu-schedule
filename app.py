# ==================== AUTH ====================
def admin_required(f):
    @wraps(f)
    def wrapper(*args, **kwargs):
        if not session.get("is_admin"):
            return redirect(url_for("admin_login"))
        return f(*args, **kwargs)
    return wrapper


# ==================== INPUT VALIDATION ====================
GROUP_RE = re.compile(r'^[A-Za-zА-Яа-я0-9_\-]{1,40}$')

def is_valid_group(g: str) -> bool:
    return bool(g and GROUP_RE.match(g))


# ==================== PUBLIC ROUTES ====================
@app.route("/")
def index():
    groups = list_groups()
    saved_group = request.cookies.get("group")
    if saved_group and is_valid_group(saved_group) and saved_group in groups:
        return redirect(url_for("schedule", group=saved_group))
    return render_template("index.html", groups=groups)


@app.route("/schedule")
def schedule():
    group = request.args.get("group", "").strip()
    remember = request.args.get("remember") == "1"

    if not is_valid_group(group):
        flash("Invalid group name.", "error")
        return redirect(url_for("index"))

    data = get_schedule(group)
    if not data:
        flash("Schedule not found.", "error")
        return redirect(url_for("index"))

    days = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday"]
    all_times = set()
    for d in days:
        for t in data.get(d, {}).get("time_slots", {}).keys():
            all_times.add(t)
    all_times = sorted(all_times, key=lambda x: x.split('-')[0])

    resp = make_response(render_template(
        "schedule.html",
        group=group, data=data, days=days, times=all_times
    ))

    if remember:
        resp.set_cookie("group", group, max_age=60*60*24*365,
                        httponly=True, samesite="Lax")
    else:
        resp.delete_cookie("group")
    return resp


