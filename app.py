# ==================== DATABASE ====================
def init_db():
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS schedules (
                group_name  TEXT PRIMARY KEY,
                schedule    TEXT NOT NULL,
                pdf_name    TEXT,
                uploaded_at TEXT DEFAULT CURRENT_TIMESTAMP
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS settings (
                key   TEXT PRIMARY KEY,
                value TEXT NOT NULL
            )
        """)
        # Default settings if missing
        defaults = {
            "current_year": "26",     # reference year (2-digit)
            "max_age_years": "5",     # delete groups older than this many years
        }
        for k, v in defaults.items():
            conn.execute(
                "INSERT OR IGNORE INTO settings (key, value) VALUES (?, ?)",
                (k, v)
            )
        conn.commit()


# -------- schedules --------
def save_schedule(group_name: str, schedule: dict, pdf_name: str = ""):
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute(
            "INSERT OR REPLACE INTO schedules (group_name, schedule, pdf_name) "
            "VALUES (?, ?, ?)",
            (group_name, json.dumps(schedule, ensure_ascii=False), pdf_name)
        )
        conn.commit()


def get_schedule(group_name: str):
    with sqlite3.connect(DB_PATH) as conn:
        row = conn.execute(
            "SELECT schedule FROM schedules WHERE group_name = ?",
            (group_name,)
        ).fetchone()
    return json.loads(row[0]) if row else None


def list_groups():
    with sqlite3.connect(DB_PATH) as conn:
        rows = conn.execute(
            "SELECT group_name FROM schedules ORDER BY group_name"
        ).fetchall()
    return [r[0] for r in rows]


def delete_group(group_name: str):
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute("DELETE FROM schedules WHERE group_name = ?", (group_name,))
        conn.commit()


# -------- settings --------
def get_setting(key: str, default: str = "") -> str:
    with sqlite3.connect(DB_PATH) as conn:
        row = conn.execute(
            "SELECT value FROM settings WHERE key = ?", (key,)
        ).fetchone()
    return row[0] if row else default


def set_setting(key: str, value: str):
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute(
            "INSERT OR REPLACE INTO settings (key, value) VALUES (?, ?)",
            (key, str(value))
        )
        conn.commit()


def get_all_settings() -> dict:
    with sqlite3.connect(DB_PATH) as conn:
        rows = conn.execute("SELECT key, value FROM settings").fetchall()
    return {k: v for k, v in rows}


