def parse_user_agent(ua: str):
    """Very small User-Agent parser -> (browser, os, device)."""
    low = (ua or "").lower()

    if "windows nt 10" in low or "windows nt 11" in low:
        os_name = "Windows 10/11"
    elif "windows" in low:
        os_name = "Windows"
    elif "android" in low:
        os_name = "Android"
