import sqlite3
conn = sqlite3.connect('schedules.db')
cur = conn.cursor()
cur.execute("select count(*) from classes where dates='[]' or dates is null")
print(cur.fetchone()[0])
cur.execute("select count(*) from classes where discipline like '%кселератор%'")
print(cur.fetchone()[0])
cur.execute("select count(*) from classes where discipline like '%кселератор%' and (dates='[]' or dates is null)")
print(cur.fetchone()[0])
cur.execute("select count(*) from classes where not (discipline like '%кселератор%') and (dates='[]' or dates is null)")
print(cur.fetchone()[0])
conn.close()
